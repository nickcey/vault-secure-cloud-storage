# ── Traduction côté serveur (courriels) : même algorithme que vault-i18n.js ──

_PATS = [(re.compile('^' + p + '$', re.S), r) for p, r in PATTERNS]
_INLINE = [(re.compile(p), r) for p, r in INLINE]
_FRAG_KEYS = sorted((k for k in PHRASES if ' ' in k and len(k) >= 8), key=len, reverse=True)
_FRAG = re.compile(r'(?<!\w)(' + '|'.join(re.escape(k) for k in _FRAG_KEYS) + r')(?!\w)')


def _fill(repl, m, depth):
    def sub(g):
        idx, raw = int(g.group(2)), g.group(1) == '$'
        val = m.group(idx) or ''
        return val if raw else _core(val, depth + 1)
    return re.sub(r'([$]|\{)(\d)\}?', sub, repl)


def _core(s, depth=0):
    if not s or depth > 3:
        return s
    if s in PHRASES:
        return PHRASES[s]
    for rx, repl in _PATS:
        m = rx.match(s)
        if m:
            return _fill(repl, m, depth)
    return _FRAG.sub(lambda m: PHRASES[m.group(1)], s) if _FRAG_KEYS else s


def translate(text, lang='en'):
    """Traduit un texte français vers l'anglais (inchangé si lang != 'en')."""
    if lang != 'en' or not text:
        return text
    lines = []
    for line in str(text).split('\n'):
        lead = line[:len(line) - len(line.lstrip())]
        trail = line[len(line.rstrip()):]
        core = re.sub(r'\s+', ' ', line.strip())
        out = _core(core)
        for rx, repl in _INLINE:
            out = rx.sub(lambda m, r=repl: re.sub(r'\$(\d)', lambda g: m.group(int(g.group(1))) or '', r), out)
        lines.append(lead + out + trail if core else line)
    return '\n'.join(lines)
